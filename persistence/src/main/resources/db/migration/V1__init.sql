-- Lab 8: base schema. Hibernate does not create tables (ddl-auto=none); Flyway owns the schema.

CREATE TABLE books (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title    VARCHAR(255) NOT NULL,
    author   VARCHAR(255) NOT NULL,
    pub_year INT          NOT NULL,
    CONSTRAINT ck_books_year CHECK (pub_year BETWEEN 1 AND 9999)
);

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64)  NOT NULL,
    password VARCHAR(100) NOT NULL,
    role     VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT        NOT NULL,
    user_id    BIGINT,
    author     VARCHAR(64)   NOT NULL,
    text       VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Many comments -> one book; comments disappear together with the book.
    CONSTRAINT fk_comments_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,
    -- Many comments -> one user; comments are kept when the account is deleted.
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_comments_book_created ON comments (book_id, created_at);
CREATE INDEX idx_comments_user_created ON comments (user_id, created_at);
